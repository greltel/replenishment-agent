# Main
# ============================================================
def main():
    parser = argparse.ArgumentParser(
        description="Backtest As-Is vs To-Be with realistic cost scenarios."
    )
    parser.add_argument("--window-days", type=int, default=60,
                        help="Backtest window in days (default 60, as in the thesis)")
    parser.add_argument("--end", type=str, default=None,
                        help="End date YYYY-MM-DD (default: the dataset's as-of date, "
                             "i.e. the latest stock snapshot / movement)")
    parser.add_argument("--scenario", type=str, default="realistic",
                        choices=list(SCENARIOS.keys()),
                        help="Cost scenario (default: realistic)")
    parser.add_argument("--all-scenarios", action="store_true",
                        help="Run all 3 scenarios and produce a comparison")
    parser.add_argument("--sensitivity", action="store_true",
                        help="Run sensitivity analysis (LT, demand, holding)")
    parser.add_argument("--forecast-method", type=str, default="moving_average",
                        choices=["moving_average", "simple_average", "exponential_smoothing", "auto"],
                        help="Forecasting method of the To-Be agent (default moving_average)")
    parser.add_argument("--by-pattern", action="store_true",
                        help="Evaluate per demand pattern (to-order materials as "
                             "backorders, KPIs per pattern) also with DEMAND_POLICY=legacy, "
                             "so that the two policies are measured the same way")
    parser.add_argument("--out", type=str, default="validation_report.csv")
    args = parser.parse_args()
    by_pattern = True if args.by_pattern else None

    end = date.fromisoformat(args.end) if args.end else get_effective_today()
    # Window of exactly `window_days` days, inclusive of both ends
    start = end - timedelta(days=args.window_days - 1)

    log.info(f"Backtest window: {start} → {end} ({args.window_days} days)")

    repo = Repository()
    materials_df = pd.read_sql("SELECT * FROM materials", repo.engine)

    out_dir = Path(args.out).parent if Path(args.out).parent != Path("") else Path(".")
    out_dir.mkdir(parents=True, exist_ok=True)
    out_base = Path(args.out).stem  # filename without extension

    # ─── Path 1: All scenarios comparison ───
    if args.all_scenarios:
        log.info("Running ALL scenarios (conservative / realistic / aggressive)...")
        all_results = []
        for scen_name in SCENARIOS:
            scen = get_scenario(scen_name)
            log.info(f"  Scenario: {scen_name} — {scen.description}")
            asis, tobe = run_scenario(repo, materials_df, start, end, scen,
                                      by_pattern=by_pattern)
            print_comparison_report(asis, tobe, scen_name)
            all_results.append((f"{scen_name}_asis", asis))
            all_results.append((f"{scen_name}_tobe", tobe))

        pivot = sensitivity_pivot(all_results)
        all_path = out_dir / f"{out_base}_all_scenarios.csv"
        pivot.to_csv(all_path, index=False)
        log.success(f"Cross-scenario comparison saved to {all_path.absolute()}")

        print(f"\n{'═' * 70}")
        print("  Cross-Scenario Summary (key metrics)")
        print(f"{'═' * 70}")
        print(pivot.to_string(index=False))

    # ─── Path 2: Sensitivity ───
    elif args.sensitivity:
        scen = get_scenario(args.scenario)
        sens_df = run_sensitivity_analysis(repo, materials_df, start, end, scen,
                                           by_pattern=by_pattern)
        sens_path = out_dir / f"{out_base}_sensitivity.csv"
        sens_df.to_csv(sens_path, index=False)

        print(f"\n{'═' * 70}")
        print(f"  Sensitivity Analysis (base scenario: {args.scenario})")
        print(f"{'═' * 70}")
        print(sens_df.to_string(index=False))
        log.success(f"Sensitivity report saved to {sens_path.absolute()}")

    # ─── Path 3: Single scenario (default) ───
    else:
        scen = get_scenario(args.scenario)
        log.info(f"Scenario: {args.scenario} — {scen.description}")
        log.info(
            f"  Holding rate breakdown: capital={scen.holding.capital_cost_rate:.0%}, "
            f"warehouse={scen.holding.warehouse_rate:.0%}, "
            f"obsolescence={scen.holding.obsolescence_rate:.0%}, "
            f"total={scen.holding.total_rate:.0%}"
        )
        asis, tobe = run_scenario(repo, materials_df, start, end, scen,
                                  forecast_method=args.forecast_method,
                                  by_pattern=by_pattern)
        df = print_comparison_report(asis, tobe, args.scenario)

        out_path = Path(args.out)
        df.to_csv(out_path, index=False)
        log.success(f"Report written to {out_path.absolute()}")

        # Per-ABC breakdown (thesis Table 4.8) as its own CSV
        abc_rows = []
        for cls in sorted(set(asis.by_abc_class) | set(tobe.by_abc_class)):
            a = asis.by_abc_class.get(cls, {})
            t = tobe.by_abc_class.get(cls, {})
            abc_rows.append({
                "abc_class":     cls,
                "n_materials":   a.get("n_materials") or t.get("n_materials"),
                "asis_tco":      a.get("tco"),
                "tobe_tco":      t.get("tco"),
                "savings":       round((a.get("tco") or 0) - (t.get("tco") or 0), 2),
                "savings_pct":   (round(((a.get("tco") or 0) - (t.get("tco") or 0))
                                        / a["tco"] * 100, 2)
                                  if a.get("tco") else None),
                "asis_service":  a.get("cycle_service_level"),
                "tobe_service":  t.get("cycle_service_level"),
                "asis_holding":  a.get("holding_cost"),
                "tobe_holding":  t.get("holding_cost"),
                "asis_stockout": a.get("stockout_cost"),
                "tobe_stockout": t.get("stockout_cost"),
            })
        if abc_rows:
            abc_path = out_dir / f"{out_base}_abc.csv"
            pd.DataFrame(abc_rows).to_csv(abc_path, index=False)
            log.success(f"Per-ABC report written to {abc_path.absolute()}")

        # Per demand pattern (DEMAND_POLICY=pattern or --by-pattern)
        if asis.by_demand_pattern or tobe.by_demand_pattern:
            pattern_path = out_dir / f"{out_base}_pattern.csv"
            pattern_breakdown(asis, tobe).to_csv(pattern_path, index=False)
            log.success(f"Per-pattern report written to {pattern_path.absolute()}")

    repo.close()


if __name__ == "__main__":
    main()
