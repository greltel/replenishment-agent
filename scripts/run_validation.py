# Reporting
# ============================================================
def print_comparison_report(
    asis: KPIReport, tobe: KPIReport, scenario_name: str = ""
) -> pd.DataFrame:
    """Print and return the comparison DataFrame."""
    df = compare_scenarios(asis, tobe)

    print(f"\n{'═' * 70}")
    print(f"  Scenario: {scenario_name.upper()}")
    print(f"  Cost basis: {asis.period_days}-day window "
          f"(holding = avg inventory value × annual rate × {asis.period_days}/365; "
          f"annualised equivalents in *_annualized rows)")
    print(f"{'═' * 70}")

    # Group by category for prettier output
    sl_metrics = ["cycle_service_level_pct", "fill_rate_pct", "stockout_days"]
    cost_metrics = ["holding_cost_eur", "capital_cost_eur", "warehouse_cost_eur",
                    "obsolescence_cost_eur", "stockout_cost_eur",
                    "lost_sales_eur", "expedite_premium_eur", "ordering_cost_eur",
                    "total_cost_of_ownership",
                    "holding_cost_annualized_eur", "tco_annualized_eur"]
    op_metrics = ["inventory_turns", "avg_inventory_eur", "days_of_cover_avg",
                  "n_orders", "avg_order_size"]

    def _print_section(title: str, metrics: list):
        print(f"\n  ── {title} ──")
        sub = df[df["metric"].isin(metrics)]
        if not sub.empty:
            print(sub.to_string(index=False))

    _print_section("Service-Level KPIs", sl_metrics)
    _print_section(f"Cost KPIs (€, {asis.period_days}-day window)", cost_metrics)
    _print_section("Operational KPIs", op_metrics)

    # Per-ABC breakdown if present
    if asis.by_abc_class or tobe.by_abc_class:
        print(f"\n  ── Per ABC Class ──")
        _print_abc_breakdown(asis.by_abc_class, tobe.by_abc_class)

    # Evaluation per demand pattern
    if asis.by_demand_pattern or tobe.by_demand_pattern:
        print("\n  ── Per demand pattern (RARE / NONE: bought to order — service = "
              "backorders, not in the availability KPIs) ──")
        print(pattern_breakdown(asis, tobe).to_string(index=False))
        a, t = asis.backorders or {}, tobe.backorders or {}
        print(f"\n  Backorders of to-order materials (customer waits for the purchase): "
              f"As-Is {a.get('lines', 0)} lines / {a.get('quantity', 0):g} units, "
              f"To-Be {t.get('lines', 0)} lines / {t.get('quantity', 0):g} units")

    return df


PATTERN_ORDER = list(dp.PATTERNS)


def pattern_breakdown(asis: KPIReport, tobe: KPIReport) -> pd.DataFrame:
    """As-Is vs To-Be per demand pattern (one row per pattern)."""
    rows = []
    keys = set(asis.by_demand_pattern) | set(tobe.by_demand_pattern)
    for pat in sorted(keys, key=lambda p: PATTERN_ORDER.index(p) if p in PATTERN_ORDER else 99):
        a = asis.by_demand_pattern.get(pat, {})
        t = tobe.by_demand_pattern.get(pat, {})
        rows.append({
            "demand_pattern":  pat,
            "n_materials":     a.get("n_materials") or t.get("n_materials"),
            "asis_service":    a.get("cycle_service_level"),
            "tobe_service":    t.get("cycle_service_level"),
            "asis_fill_rate":  a.get("fill_rate"),
            "tobe_fill_rate":  t.get("fill_rate"),
            "asis_avg_inventory": a.get("avg_inventory"),
            "tobe_avg_inventory": t.get("avg_inventory"),
            "asis_holding":    a.get("holding_cost"),
            "tobe_holding":    t.get("holding_cost"),
            "asis_lost_sales": a.get("lost_sales"),
            "tobe_lost_sales": t.get("lost_sales"),
            "asis_orders":     a.get("n_orders"),
            "tobe_orders":     t.get("n_orders"),
            "asis_backorder_lines": a.get("backorder_lines"),
            "tobe_backorder_lines": t.get("backorder_lines"),
            "asis_tco":        a.get("tco"),
            "tobe_tco":        t.get("tco"),
            "savings":         round((a.get("tco") or 0) - (t.get("tco") or 0), 2),
        })
    return pd.DataFrame(rows)


def _print_abc_breakdown(asis_abc: dict, tobe_abc: dict) -> None:
    classes = sorted(set(asis_abc.keys()) | set(tobe_abc.keys()))
    rows = []
    for cls in classes:
        a = asis_abc.get(cls, {})
        t = tobe_abc.get(cls, {})
        rows.append({
            "ABC":            cls,
            "n_materials":    a.get("n_materials") or t.get("n_materials"),
            "service_asis":   a.get("cycle_service_level"),
            "service_tobe":   t.get("cycle_service_level"),
            "holding_asis":   a.get("holding_cost"),
            "holding_tobe":   t.get("holding_cost"),
            "stockout_asis":  a.get("stockout_cost"),
            "stockout_tobe":  t.get("stockout_cost"),
            "tco_asis":       a.get("tco"),
            "tco_tobe":       t.get("tco"),
            "savings":        (round(a["tco"] - t["tco"], 2)
                               if a.get("tco") is not None and t.get("tco") is not None
                               else None),
        })
    if rows:
        print(pd.DataFrame(rows).to_string(index=False))


